using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;

namespace SslrExperience
{
    public class Program
    {
        static Lazy<Settings> _LazySettings = null!;
        public static Settings Settings => _LazySettings.Value;

        public static async Task<int> Main(string[] args)
        {
            return await SynthesisPipeline.Instance
                .SetAutogeneratedSettings(nickname: "Settings", path: "Settings.json", out _LazySettings)
                .SetTypicalOpen(GameRelease.SkyrimSE, "SSLR_Experience_Patch.esp")
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
                .Run(args);
        }

        public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            bool patched = false;

            patched |= SetGameSetting(state, "fXPLevelUpBase", Settings.General.LevelUpXPBase);
            patched |= SetGameSetting(state, "fXPLevelUpMult", Settings.General.LevelUpXPMult);
            patched |= QuestPatcher.RunPatch(state, Settings);
            patched |= RacePatcher.RunPatch(state, Settings);
            patched |= SkillPatcher.RunPatch(state, Settings);
            patched |= SkillRateText.RunPatch(state, Settings);
            if (!patched)
            {
                state.PatchMod.Clear();
            }

            WriteExperienceIni(state);
        }

        /// <summary>Overrides the winning GMST by EditorID instead of adding a duplicate record.</summary>
        static bool SetGameSetting(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, string editorId, float value)
        {
            var winner = state.LoadOrder.PriorityOrder.GameSetting().WinningOverrides()
                .OfType<IGameSettingFloatGetter>()
                .FirstOrDefault(g => editorId.Equals(g.EditorID, StringComparison.OrdinalIgnoreCase));
            if (winner == null)
            {
                state.PatchMod.GameSettings.Add(new GameSettingFloat(state.PatchMod, editorId) { Data = value });
                Console.WriteLine($"{editorId}: added = {value}");
                return true;
            }
            if (winner.Data == value) return false;
            var gmst = (GameSettingFloat)state.PatchMod.GameSettings.GetOrAddAsOverride((IGameSettingGetter)winner);
            Console.WriteLine($"{editorId}: {winner.Data} => {value}");
            gmst.Data = value;
            return true;
        }

        static readonly string[] LegacyKeys =
        {
            "bForceLvlMeter", "bLocClearingFix", "iXPObjectives", "iXPLevelRange", "fXPKillingMult", "fXPGroupFactor", "fXPReadingMult",
            "iXPDiscImperialCamp", "iXPDiscStormcloakCamp", "iXPDiscCapitol", "iXPDiscRavenRock", "iXPDiscStandingStones",
            "iXPClearImperialCamp", "iXPClearStormcloakCamp", "iXPClearCapitol", "iXPClearRavenRock", "iXPClearStandingStones",
        };

        static void WriteExperienceIni(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            var path = Path.Combine(state.DataFolderPath, "SKSE", "Plugins", "Experience.ini");
            if (!File.Exists(path))
            {
                Console.WriteLine($"WARN: {path} not found - is Experience installed? Writing a partial Experience.ini.");
            }
            var ini = ExperienceIni.Load(path);
            static string F(float v) => v.ToString("0.000000", CultureInfo.InvariantCulture);

            // Experience 2.x keys that 3.x renamed or dropped (left behind by older presets)
            int legacy = LegacyKeys.Sum(ini.Remove);
            if (legacy > 0) Console.WriteLine($"Removed {legacy} Experience 2.x keys");

            string? presetFile = Settings.General.Preset switch
            {
                General.ExperiencePreset.TrueUnlevelled => "Preset_TrueUnlevelled.ini",
                General.ExperiencePreset.ExtraRewarding => "Preset_ExtraRewarding.ini",
                _ => null,
            };
            if (presetFile != null)
            {
                var presetPath = Path.Combine(state.ExtraSettingsDataPath!, presetFile);
                Console.WriteLine($"Merging preset {presetPath}");
                foreach (var (section, key, value) in ExperienceIni.ReadPairs(presetPath))
                {
                    ini.Set(section, key, value);
                }
            }

            if (Settings.SkillCaps.WriteSkillCaps)
            {
                ini.Set("General", "fSkillCapBase", F(Settings.SkillCaps.SkillCapBase));
                ini.Set("General", "fSkillCapMult", F(Settings.SkillCaps.SkillCapMult));
                ini.Set("General", "bUseRacialCaps", Settings.SkillCaps.UseRacialCaps ? "true" : "false");
                if (Settings.SkillCaps.MaxPlayerLevel > 0)
                {
                    ini.Set("General", "iMaxPlayerLevel", Settings.SkillCaps.MaxPlayerLevel.ToString(CultureInfo.InvariantCulture));
                }
                Console.WriteLine($"Skill caps: {Settings.SkillCaps.SkillCapBase} + {Settings.SkillCaps.SkillCapMult} x level, racial = {Settings.SkillCaps.UseRacialCaps}");
            }
            if (Settings.SkillSettings.SuppressSkillGains)
            {
                ini.Set("General", "bEnableSkillXP", "false");
            }

            Console.WriteLine($"Writing {path}");
            ini.Save(path);
        }
    }
}
